#!/usr/bin/env python3
"""
============================================================================
 ANASTOMOSIS.MD — BRAND MARK RENDERER
============================================================================
 Draws the brand mark from NOTHING: every letter, branch, twig and root
 is generated by this file. Nothing is copied from any previous image.

 What it draws
 -------------
   * a 1024x1024 bone field (#F7F3EB) with paper grain
   * the word "anastomosis" as 11 branch-letter glyphs riding an arc:
       letters 1-4  "anas"   -> arterial crimson
       letters 5-11 "tomosis" -> venous petrol
     (no ".md" — founder decision)
   * a tapering trunk with a lean, root flare with sub-roots
   * a recursive canopy: 12 crown limbs + 58 filler sprigs
   * a soft paper halo behind each letter so the branches never eat them
   * a feathered radial trim so the mark is circle-crop safe (favicons,
     avatars, round social crops)

 The letters sit at the arc anchors but stand UPRIGHT — the italic cut of
 Instrument Serif supplies all the lean. That is why the word reads.

 Why the spelling cannot break
 -----------------------------
 The letters are drawn glyph-by-glyph from the string LETTERS below, in
 order, one glyph per anchor in SLOTS. There is no image, no trace, no
 transplant. If this file says "anastomosis", the picture says it too.

 How to run
 ----------
   pip install pillow numpy
   python render-mark.py                     -> mark-rendered.png (here)
   python render-mark.py --out my-mark.png
   python render-mark.py --seed 7            -> same design, new twig roll
   python render-mark.py --letter-size 200

 Every run also writes <out>-proof.png — the letter pass typeset flat in
 a row, same glyphs the mark uses. That strip is the spelling proof: what
 you read there is exactly what the branches spell.

 Needs the font InstrumentSerif-Italic.ttf next to this file, or at
 ../social-kit/fonts/ (it is in the repo), or pass --font /path/to/it.ttf
 (Google Fonts, SIL Open Font License).

 The knobs you are most likely to want are in the TUNABLES block right
 below. The run ends with an audit report — check the PASS lines.
============================================================================
"""

import argparse
import math
import os
import random
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont
import numpy as np

# ============================================================================
#  TUNABLES — edit these
# ============================================================================

SEED         = 20261030   # twig/root roll. Same seed = identical output.
CANVAS       = 1024       # canvas edge in px

# ---- palette (brand tokens) ------------------------------------------------
BONE         = (247, 243, 235)   # #F7F3EB  the field, always
CRIMSON      = (152, 51, 44)     # letters "anas"  (arterial)
PETROL       = (50, 88, 97)      # letters "tomosis" + all the wood (venous)
HALO_TINT    = (255, 252, 243)   # soft paper glow behind each letter

# ---- the word --------------------------------------------------------------
# If you ever change LETTERS you must change SLOTS to match (one anchor per
# letter, in reading order) — the script refuses to run otherwise.
LETTERS      = "anastomosis"

# Reading arc: where each letter sits (x, y), lower-left -> over the crown
# -> down the right side. Move the anchors to reshape the arc; the letters
# stay upright wherever you put them.
SLOTS = [
    (139, 385),   # 1  a
    (229, 290),   # 2  n
    (352, 219),   # 3  a
    (459, 190),   # 4  s
    (549, 161),   # 5  t
    (653, 184),   # 6  o
    (743, 232),   # 7  m
    (798, 278),   # 8  o
    (857, 336),   # 9  s
    (874, 411),   # 10 i
    (875, 502),   # 11 s
]
CRIMSON_COUNT = 4          # first N letters are crimson, rest petrol
LETTER_SIZE   = 234        # glyph px size (234 matches the shipped mark)
LETTER_TILT   = 0.0        # extra degrees applied to EVERY letter
LETTER_WOBBLE = 3.5        # +/- deg of random tilt per glyph
LETTER_DRIFT  = 5.0        # +/- px of random drift per glyph
LETTER_DILATE = 5          # MaxFilter size — how much the ink spreads
HALO          = True       # soft paper glow behind letters (keeps them
                           # readable where branches pass behind them)
HALO_GROW    = 9           # how far the halo extends past the glyph
HALO_SOFT    = 6           # halo blur radius

# ---- trunk -----------------------------------------------------------------
TRUNK_TOP    = (443, 612)  # where it leaves the crown
TRUNK_BASE   = (465, 905)  # where it meets the roots
TRUNK_W_TOP  = 34          # px wide at the top (branches taper: thin up top)
TRUNK_W_BASE = 47          # px wide at the base
TRUNK_BOW    = 16          # sideways bow of the trunk centerline (px)

# ---- roots -----------------------------------------------------------------
ROOT_COUNT   = 9           # main roots fanning from the trunk base
ROOT_LEN     = (125, 290)  # min/max main-root length (px)
ROOT_W       = (8, 14)     # min/max root thickness at the base
ROOT_SPREAD  = 72          # deg — total fan left+right of straight down

# ---- canopy ----------------------------------------------------------------
CROWN_CENTER = (505, 272)  # heart of the canopy
CROWN_RX     = 420         # horizontal radius
CROWN_RY     = 207         # vertical radius
CROWN_LIMBS  = 12          # big limbs radiating up from the trunk top
LIMB_JUNCTION = (447, 548) # where the limbs meet (inside the crown)
LIMB_FAN     = 160         # deg — how wide the limbs spread across the sky
LIMB_LEN     = (130, 185)  # min/max first-segment length
LIMB_W       = (10, 13)    # limb thickness at its base
LIMB_DEPTH   = 3           # recursion depth of each limb
SPRIGS       = 58          # filler twigs scattered through the canopy
SPRIG_LEN    = (16, 42)    # min/max sprig length
SPRIG_W      = (3.2, 5.2)  # sprig thickness
SPRIG_DEPTH  = 2           # recursion depth of each sprig
BRANCH_SPREAD = 26         # deg — how wide children splay from a parent
SHRINK       = 0.68        # child thickness / parent thickness

# ---- finish ----------------------------------------------------------------
WOOD_DILATE  = 3           # MaxFilter size for wood strokes (branch weight)
GRAIN        = 2.5         # paper grain noise sigma (0 = off)
TRIM_RADIUS  = 508         # keep all ink inside this radius (circle crops)
TRIM_FEATHER = 10          # softness of that trim
SAFE         = (85, 95, 940, 950)   # wood control points are clamped into
                                    # this box: x0, y0, x1, y1

# ============================================================================
#  RENDERER — below here you rarely need to touch anything
# ============================================================================

def find_font(explicit):
    here = os.path.dirname(os.path.abspath(__file__))
    cands = []
    if explicit:
        cands.append(explicit)
    cands += [
        os.path.join(here, "InstrumentSerif-Italic.ttf"),
        os.path.join(here, "social-kit", "fonts", "InstrumentSerif-Italic.ttf"),
        os.path.join(here, "..", "social-kit", "fonts", "InstrumentSerif-Italic.ttf"),
        os.path.join(os.getcwd(), "InstrumentSerif-Italic.ttf"),
        os.path.join(os.getcwd(), "social-kit", "fonts", "InstrumentSerif-Italic.ttf"),
    ]
    for c in cands:
        if c and os.path.exists(c):
            return c
    sys.exit("font not found: put InstrumentSerif-Italic.ttf next to this "
             "script (or pass --font). It ships in social-kit/fonts/.")


def clamp_pt(x, y):
    x0, y0, x1, y1 = SAFE
    return (min(max(x, x0), x1), min(max(y, y0), y1))


def wobble_path(rng, p0, p1, bow, n=26):
    """A bowed, slightly noisy curve from p0 to p1 (organic, not ruler-straight)."""
    x0, y0 = p0
    x1, y1 = p1
    dx, dy = x1 - x0, y1 - y0
    length = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / length, dx / length                 # unit normal
    mx, my = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    cx, cy = mx + nx * bow, my + ny * bow              # control point
    pts = []
    for i in range(n + 1):
        t = i / n
        bx = (1 - t) ** 2 * x0 + 2 * (1 - t) * t * cx + t ** 2 * x1
        by = (1 - t) ** 2 * y0 + 2 * (1 - t) * t * cy + t ** 2 * y1
        pts.append((bx + rng.uniform(-1, 1) * 1.6,
                    by + rng.uniform(-1, 1) * 1.6))
    return pts


def draw_tapered(draw, pts, w0, w1, fill=255):
    """Polyline that gets thinner (or thicker) from end to end."""
    n = len(pts)
    for i in range(n - 1):
        w = w0 + (w1 - w0) * (i / max(1, n - 2))
        x, y = pts[i]
        r = w / 2.0
        draw.ellipse([x - r, y - r, x + r, y + r], fill=fill)
        x2, y2 = pts[i + 1]
        if w >= 2.0:
            draw.line([(x, y), (x2, y2)], fill=fill, width=int(round(w)))


def grow(rng, draw, x, y, ang_deg, length, thick, depth,
         upward=False, bow_frac=0.20):
    """Recursive branch: one wobbled tapered segment, then children.

    upward=True keeps every child seeking skyward (limbs never droop
    below the crown line) — the under-crown stays airy.
    """
    if depth <= 0 or thick < 1.3 or length < 6:
        return
    ex = x + math.cos(math.radians(ang_deg)) * length
    ey = y + math.sin(math.radians(ang_deg)) * length
    ex, ey = clamp_pt(ex, ey)
    bow = rng.uniform(-bow_frac, bow_frac) * length
    pts = wobble_path(rng, (x, y), (ex, ey), bow)
    draw_tapered(draw, pts, thick, thick * 0.72)
    if depth <= 1:
        return
    kids = rng.choice((2, 2, 3))
    for j in range(kids):
        na = (ang_deg
              + (j - (kids - 1) / 2.0) * BRANCH_SPREAD * 0.9
              + rng.uniform(-1, 1) * BRANCH_SPREAD * 0.5)
        if upward:                          # phototropism: -179..-1 deg only
            na = max(-179.0, min(-1.0, na))
        grow(rng, draw, ex, ey, na,
             length * rng.uniform(0.58, 0.80),
             thick * SHRINK, depth - 1, upward=upward, bow_frac=bow_frac)


def glyph_tile(ch, font, size, rng, wobble, drift, dilate):
    """One letter: rendered, fattened, tilted (upright + wobble by default)."""
    pad = size
    tile = Image.new("L", (size + 2 * pad, size + 2 * pad), 0)
    td = ImageDraw.Draw(tile)
    td.text((tile.width // 2, tile.height // 2), ch, font=font, fill=255,
            anchor="mm")
    if dilate:
        tile = tile.filter(ImageFilter.MaxFilter(dilate))
    rot = LETTER_TILT + rng.uniform(-wobble, wobble)
    tile = tile.rotate(rot, resample=Image.BICUBIC, expand=True)
    dx, dy = rng.uniform(-drift, drift), rng.uniform(-drift, drift)
    return tile, int(round(dx)), int(round(dy))


def proof_strip(font, letter_size, out):
    """Typeset the letter pass flat on one baseline, same string, font,
    size, colors and dilation the mark itself uses. This is the spelling
    proof: what you read here is exactly what the branches spell.
    (OCR-friendly on purpose — one baseline, natural spacing.)"""
    head, tail = LETTERS[:CRIMSON_COUNT], LETTERS[CRIMSON_COUNT:]
    W = int(font.getlength(LETTERS)) + 90
    H = letter_size + 90
    base = H - 45
    x0 = 45
    strip = Image.new("RGB", (W, H), BONE)
    for text, color in ((head, CRIMSON), (tail, PETROL)):
        mask = Image.new("L", (W, H), 0)
        ImageDraw.Draw(mask).text((x0, base), text, font=font, fill=255,
                                  anchor="ls")
        mask = mask.filter(ImageFilter.MaxFilter(LETTER_DILATE))
        layer = Image.new("RGB", (W, H), color)
        strip = Image.composite(layer, strip, mask)
        x0 += font.getlength(text)
    strip.save(out)
    return out


def render(seed=SEED, letter_size=LETTER_SIZE, font_path=None, halo=HALO,
           out="mark-rendered.png"):
    rng = random.Random(seed)

    if len(LETTERS) != len(SLOTS):
        sys.exit("LETTERS has %d characters but SLOTS has %d anchors — they "
                 "must match 1:1." % (len(LETTERS), len(SLOTS)))

    font = ImageFont.truetype(find_font(font_path), letter_size)

    # ---- 1. bone field ----------------------------------------------------
    field = Image.new("RGB", (CANVAS, CANVAS), BONE)

    # ---- 2. wood: trunk, roots, canopy (a mask we tint petrol) -----------
    wood = Image.new("L", (CANVAS, CANVAS), 0)
    wd = ImageDraw.Draw(wood)

    # trunk — one bowed tapered stroke, thin at the top, thick at the base
    trunk_pts = wobble_path(rng, TRUNK_TOP, TRUNK_BASE, TRUNK_BOW, n=40)
    draw_tapered(wd, trunk_pts, TRUNK_W_TOP, TRUNK_W_BASE)

    # roots — fan from the trunk base, each with sub-rootlets
    base_x, base_y = TRUNK_BASE
    for i in range(ROOT_COUNT):
        t = (i + 0.5) / ROOT_COUNT
        ang = 90 + (t - 0.5) * 2 * ROOT_SPREAD + rng.uniform(-7, 7)
        ln = rng.uniform(*ROOT_LEN)
        w = rng.uniform(*ROOT_W)
        ex = base_x + math.cos(math.radians(ang)) * ln
        ey = base_y + math.sin(math.radians(ang)) * ln
        pts = wobble_path(rng, (base_x, base_y - 8), clamp_pt(ex, ey),
                          rng.uniform(-22, 22))
        draw_tapered(wd, pts, w, w * 0.48)
        # sub-rootlets
        for _ in range(rng.choice((1, 2, 2, 3))):
            k = rng.uniform(0.35, 0.8)
            sx = pts[int(k * (len(pts) - 1))][0]
            sy = pts[int(k * (len(pts) - 1))][1]
            sa = ang + rng.uniform(-55, 55)
            sl = ln * rng.uniform(0.25, 0.5)
            spts = wobble_path(rng, (sx, sy),
                               clamp_pt(sx + math.cos(math.radians(sa)) * sl,
                                        sy + math.sin(math.radians(sa)) * sl),
                               rng.uniform(-14, 14))
            draw_tapered(wd, spts, w * 0.55, 1.3)

    # crown limbs — the 12 big branches carrying the canopy
    # (junction sits up inside the crown so limbs never spray below it)
    jx, jy = LIMB_JUNCTION
    for i in range(CROWN_LIMBS):
        ang = -90 + (i + 0.5) * (LIMB_FAN / CROWN_LIMBS) - LIMB_FAN / 2 + rng.uniform(-8, 8)
        grow(rng, wd, jx, jy, ang,
             rng.uniform(*LIMB_LEN), rng.uniform(*LIMB_W), LIMB_DEPTH,
             upward=True, bow_frac=0.12)

    # filler sprigs — scatter inside the crown ellipse (rejection sampling)
    placed = 0
    guard = 0
    while placed < SPRIGS and guard < SPRIGS * 60:
        guard += 1
        tx = rng.uniform(-1, 1)
        ty = rng.uniform(-1, 1)
        if tx * tx + ty * ty > 1.0:
            continue                              # outside the ellipse
        x = CROWN_CENTER[0] + tx * CROWN_RX
        y = CROWN_CENTER[1] + ty * CROWN_RY
        if ty > 0.72 or y > 470:
            continue                              # top-biased, airy under-crown
        grow(rng, wd, x, y, rng.uniform(0, 360),
             rng.uniform(*SPRIG_LEN), rng.uniform(*SPRIG_W), SPRIG_DEPTH)
        placed += 1

    if placed < SPRIGS:
        print("note: only %d of %d sprigs placed — crown ellipse too small "
              "for the rejection rules" % (placed, SPRIGS))

    wood = wood.filter(ImageFilter.MaxFilter(WOOD_DILATE))
    wood = wood.filter(ImageFilter.GaussianBlur(0.8))
    petrol_layer = Image.new("RGB", (CANVAS, CANVAS), PETROL)
    field = Image.composite(petrol_layer, field, wood)

    # ---- 3. letter halos (soft paper glow, drawn over the wood) -----------
    if halo:
        halo_mask = Image.new("L", (CANVAS, CANVAS), 0)
        for ch, (ax, ay) in zip(LETTERS, SLOTS):
            tile, _, _ = glyph_tile(ch, font, letter_size, rng,
                                    wobble=0.0, drift=0.0, dilate=0)
            big = Image.new("L", (CANVAS, CANVAS), 0)
            big.paste(tile, (int(ax - tile.width / 2),
                             int(ay - tile.height / 2)))
            big = big.filter(ImageFilter.MaxFilter(HALO_GROW))
            big = big.filter(ImageFilter.GaussianBlur(HALO_SOFT))
            halo_mask = ImageChops.lighter(halo_mask, big)
        glow = Image.new("RGB", (CANVAS, CANVAS), HALO_TINT)
        field = Image.composite(glow, field,
                                halo_mask.point(lambda v: int(v * 0.85)))

    # ---- 4. the letters themselves ----------------------------------------
    for i, (ch, (ax, ay)) in enumerate(zip(LETTERS, SLOTS)):
        color = CRIMSON if i < CRIMSON_COUNT else PETROL
        tile, dx, dy = glyph_tile(ch, font, letter_size, rng,
                                  wobble=LETTER_WOBBLE, drift=LETTER_DRIFT,
                                  dilate=LETTER_DILATE)
        layer = Image.new("RGB", (CANVAS, CANVAS), color)
        mask = Image.new("L", (CANVAS, CANVAS), 0)
        mask.paste(tile, (int(ax - tile.width / 2) + dx,
                          int(ay - tile.height / 2) + dy))
        field = Image.composite(layer, field, mask)

    # ---- 5. paper grain ----------------------------------------------------
    if GRAIN > 0:
        arr = np.asarray(field).astype(np.float32)
        noise = np.random.RandomState(seed + 1).normal(0, GRAIN, arr.shape)
        arr = np.clip(arr + noise, 0, 255).astype(np.uint8)
        field = Image.fromarray(arr)

    # ---- 6. feathered circle trim -----------------------------------------
    if TRIM_RADIUS:
        arr = np.asarray(field).astype(np.float32)
        yy, xx = np.mgrid[0:CANVAS, 0:CANVAS]
        r = np.sqrt((xx - CANVAS / 2.0) ** 2 + (yy - CANVAS / 2.0) ** 2)
        a = np.clip((r - (TRIM_RADIUS - TRIM_FEATHER)) / float(TRIM_FEATHER), 0, 1)
        a = a * a * (3 - 2 * a)                       # smoothstep
        bone = np.array(BONE, dtype=np.float32)
        arr = arr * (1 - a[..., None]) + bone * a[..., None]
        field = Image.fromarray(arr.astype(np.uint8))

    field.save(out)
    return out


# ----------------------------------------------------------------------------
def audit(path, proof=None):
    """Self-check: spelling (by construction), circle safety, mass, colors."""
    im = Image.open(path).convert("RGB")
    a = np.asarray(im).astype(int)
    h, w = a.shape[:2]
    bg = np.array(BONE)
    dist = np.abs(a - bg).sum(axis=2)
    ink = dist > 40
    ys, xs = np.where(ink)
    r = np.sqrt((xs - w / 2.0) ** 2 + (ys - h / 2.0) ** 2)
    rr, gg, bb = a[..., 0], a[..., 1], a[..., 2]
    crim = ink & (rr > gg + 25) & (rr > bb + 25)
    pet = ink & ~crim

    print("─" * 62)
    print("AUDIT  %s" % path)
    print("  spelling      : '%s' drawn glyph-by-glyph (%d anchors)"
          % (LETTERS, len(SLOTS)))
    if proof:
        print("  proof strip   : %s  (read it — that is the word)" % proof)
        try:
            from rapidocr_onnxruntime import RapidOCR
            res, _ = RapidOCR()(np.asarray(
                Image.open(proof).convert("RGB")))
            txt = "".join(x[1] for x in res).lower() if res else ""
            ok_s = LETTERS in txt
            print("  OCR read-back : %r  %s" % (txt, "PASS" if ok_s else "FAIL"))
        except ImportError:
            print("  OCR read-back : skipped (rapidocr not installed here)")
    print("  canvas        : %dx%d" % (w, h))
    print("  ink mass      : %.2f%%   (shipped mark: 18.2%%)"
          % (100.0 * ink.mean()))
    print("  ink bbox      : x %d-%d  y %d-%d  (safe box %s)"
          % (xs.min(), xs.max(), ys.min(), ys.max(), SAFE))
    ok_r = r.max() <= TRIM_RADIUS + 2
    print("  max radius    : %.0f px  (limit %d)  %s"
          % (r.max(), TRIM_RADIUS, "PASS" if ok_r else "FAIL"))
    print("  crimson px    : %d   petrol px : %d" % (crim.sum(), pet.sum()))
    if crim.sum() and pet.sum():
        print("  crimson core  : rgb%s" % (tuple(
            (a[crim].mean(axis=0)).round().astype(int)),))
        print("  petrol core   : rgb%s" % (tuple(
            (a[pet].mean(axis=0)).round().astype(int)),))
    print("─" * 62)
    return ok_r


def main():
    ap = argparse.ArgumentParser(description="Anastomosis.MD brand mark renderer")
    ap.add_argument("--out", default="mark-rendered.png")
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--letter-size", type=int, default=LETTER_SIZE)
    ap.add_argument("--font", default=None)
    ap.add_argument("--no-halo", action="store_true")
    ap.add_argument("--no-proof", action="store_true",
                    help="skip writing the <out>-proof.png spelling strip")
    args = ap.parse_args()

    font_path = find_font(args.font)
    font = ImageFont.truetype(font_path, args.letter_size)

    out = render(seed=args.seed, letter_size=args.letter_size,
                 font_path=font_path, halo=not args.no_halo, out=args.out)
    proof = None
    if not args.no_proof:
        root, ext = os.path.splitext(out)
        proof = proof_strip(font, args.letter_size, root + "-proof" + (ext or ".png"))
    ok = audit(out, proof)
    if not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
